public class BlocksCommand implements CommandExecutor, TabCompleter {

    private final Main plugin;

    public BlocksCommand(Main plugin){
        this.plugin = plugin;
        Objects.requireNonNull(plugin.getCommand("blocks")).setExecutor(this);
    }

    @Override
    public boolean onCommand(@NotNull CommandSender sender, @NotNull Command command, @NotNull String label, @NotNull String @NotNull [] args) {
        if (sender instanceof Player player){
            if (plugin.getMech().hasDuo(player)){
                plugin.getBlocksGUI().openGUI(player, 1);
            } else {
                player.sendMessage(Component.text("You are not in a duo yet.", NamedTextColor.RED));
            }
        }
        return false;
    }

    @Override
    public @Nullable List<String> onTabComplete(@NotNull CommandSender sender, @NotNull Command command, @NotNull String label, @NotNull String @NotNull [] args) {
        return List.of();
    }
}
